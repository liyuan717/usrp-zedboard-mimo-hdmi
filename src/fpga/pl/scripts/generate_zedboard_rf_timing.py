"""Generate the reviewed AD9361 CMOS source-synchronous timing XDC.

This tool accepts either the reviewed pre-board candidate envelope or a
board-qualified measurement record.  It never accepts an unreviewed
assumption-only profile; the generated comment and the release gate preserve
the distinction between a deployable lab candidate and hardware acceptance.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path


REQUIRED = {
    "data_clk_period_ns",
    "device_timing_source",
    "board_assumptions",
    "status",
}


def number(mapping: dict, key: str) -> float:
    value = mapping.get(key)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"missing numeric field: {key}")
    converted = float(value)
    if not math.isfinite(converted):
        raise ValueError(f"non-finite numeric field: {key}")
    return converted


def build_xdc(profile: dict) -> str:
    allowed_status = {"PREBOARD_CONSERVATIVE_APPROVED", "MEASURED_APPROVED"}
    if profile.get("status") not in allowed_status:
        raise ValueError(
            "timing XDC requires status=PREBOARD_CONSERVATIVE_APPROVED "
            "or MEASURED_APPROVED"
        )
    if profile.get("interface_mode") != "CMOS_1V8_DUAL_PORT_FULL_DUPLEX_2R2T_DDR":
        raise ValueError("timing profile is not locked to the reviewed CMOS 1.8 V 2R2T DDR mode")
    missing = REQUIRED.difference(profile)
    if missing:
        raise ValueError(f"profile missing keys: {sorted(missing)}")
    device = profile["device_timing_source"]
    board = profile["board_assumptions"]
    period = number(profile, "data_clk_period_ns")
    if period < 16.276:
        raise ValueError("CMOS DATA_CLK period must be >=16.276 ns (61.44 MHz maximum)")
    sample_rate = number(profile, "complex_sample_rate_msps_per_stream")
    if abs(sample_rate - 4.0) > 1e-9 or abs(period - 125.0) > 1e-9:
        raise ValueError("pre-board timing profile is locked to 4.00 MSPS and 8 MHz (125 ns)")
    board_min = number(board, "interconnect_data_minus_clock_min_ns")
    board_max = number(board, "interconnect_data_minus_clock_max_ns")
    margin = number(board, "io_margin_ns")
    if board_min > board_max or margin < 0:
        raise ValueError("invalid board skew or margin")
    rx_data_min = number(device, "rx_data_clk_to_output_min_ns") + board_min - margin
    rx_data_max = number(device, "rx_data_clk_to_output_max_ns") + board_max + margin
    rx_frame_min = number(device, "rx_frame_clk_to_output_min_ns") + board_min - margin
    rx_frame_max = number(device, "rx_frame_clk_to_output_max_ns") + board_max + margin
    # TX requires a measured FB_CLK/data phase envelope.  It is intentionally
    # distinct from DATA_CLK because the AD9361 specification imposes no phase
    # relationship between them.
    tx_min = number(board, "tx_data_minus_fbclk_min_ns")
    tx_max = number(board, "tx_data_minus_fbclk_max_ns")
    if tx_min > tx_max:
        raise ValueError("invalid tx_data_minus_fbclk bounds")
    tx_setup = number(device, "tx_data_setup_at_ad9361_ns")
    tx_hold = number(device, "tx_data_hold_at_ad9361_ns")
    # set_output_delay expresses receiver setup/hold at the external device
    # relative to the source-synchronous clock launched by this FPGA.  Let
    # delta be (data trace delay - FB_CLK trace delay).  The required maximum
    # is device setup + worst late data/early clock delta + margin.  The
    # required minimum is -device hold + worst early data/late clock delta
    # - margin.  Do not reverse these terms: doing so would make a data-before-
    # clock board assumption hide a real AD9361 setup requirement.
    tx_out_max = tx_setup + tx_max + margin
    tx_out_min = -tx_hold + tx_min - margin
    if tx_out_min > tx_out_max:
        raise ValueError("measured TX phase window cannot satisfy setup/hold with selected margin")
    rx_ports = "{rx_frame_in rx_data_in[*]}"
    # ENABLE/TXNRX are asynchronous mode/control pins, not members of the
    # source-synchronous TX sample bus.  Their AD9361 control-pin setup/hold
    # check is a separate board procedure and must not be disguised as FB_CLK
    # data timing.
    tx_ports = "{tx_frame_out tx_data_out[*]}"
    return "\n".join(
        [
            "# Generated by generate_zedboard_rf_timing.py; do not hand-edit.",
            f"# profile_id={profile.get('profile_id', 'unnamed')}",
            f"# profile_status={profile['status']}",
            "# Project-recorded AD9361 timing values plus recorded board profile.",
            f"set_input_delay -clock ad9361_rx_clk -min {rx_data_min:.3f} [get_ports {rx_ports}]",
            f"set_input_delay -clock ad9361_rx_clk -max {rx_data_max:.3f} [get_ports {rx_ports}]",
            "# FB_CLK is launched by the ADI CMOS-interface ODDR.  Use its C pin",
            "# as the generated-clock source: this preserves the actual BUFG/ODDR",
            "# latency shared with TX data instead of treating the output port as an",
            "# unrelated zero-latency primary clock.",
            "set ad9361_fb_clk_src [get_pins -hierarchical -filter {NAME =~ */i_tx_clk/i_tx_data_oddr/C}]",
            "if {[llength $ad9361_fb_clk_src] != 1} {error \"AD9361 FB_CLK ODDR source is missing or ambiguous\"}",
            "create_generated_clock -name ad9361_fb_clk -source $ad9361_fb_clk_src -divide_by 1 [get_ports tx_clk_out]",
            f"set_output_delay -clock ad9361_fb_clk -min {tx_out_min:.3f} [get_ports {tx_ports}]",
            f"set_output_delay -clock ad9361_fb_clk -max {tx_out_max:.3f} [get_ports {tx_ports}]",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("profile", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    profile = json.loads(args.profile.read_text(encoding="utf-8"))
    xdc = build_xdc(profile)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(xdc, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
