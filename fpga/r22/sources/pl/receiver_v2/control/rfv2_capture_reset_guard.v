`timescale 1ns/1ps
// RF capture reset/epoch coordinator.
//
// This is deliberately a small protocol controller, not another clock
// monitor.  The ADI util_wfifo writer can be reset while its reader remains
// live.  Its request toggle may then return 1->0 and replay an old RAM block.
// A raw fault therefore asynchronously quiesces BOTH interfaces.  Recovery is
// a level protocol with an explicit elastic-FIFO epoch acknowledgement; no
// request-toggle edge, timer, or software RUN transition authorises capture.
//
// Contract for integration:
//   * din_raw_reset is the active-high reset of the l_clk/write side.
//   * dout_raw_reset is the active-high reset of the FCLK/read side.
//   * pll_locked is common RF clock-lock health.  A low value is a fault.
//   * source_ready is the independent raw-clock monitor result.  A low level
//     is a common asynchronous capture fault (including a stopped l_clk), not
//     a din_clk-domain data input.  It MUST NOT be generated from this guard.
//   * capture_epoch_fence is ORed into rfv2_ingress.soft_flush.  The existing
//     registered ingress fifo_flush drives rf_rx_elastic.flush_sync.
//   * elastic_flush_ack is the registered acknowledgement from the *actual*
//     elastic FIFO.  CPACK writes stay blocked from fence issuance through
//     that ACK, so an ACK proves the new epoch has no retained flush-same-cycle
//     beat.
//   * reader_data_enable gates the elastic->ingress public stream.  It is
//     released only after the writer has restarted from reset and the read
//     side has been held reset throughout the stale-request window.
//
// The source and destination clocks may be stopped.  Assertion uses
// global_fault directly and is thus fail-closed without clocks.  Deassertion
// is local-clock state-machine work plus two-flop level synchronizers.  If one
// clock stays stopped, capture_ready stays low; this is safe waiting, not an
// unbounded fixed-delay release.
module rfv2_capture_reset_guard (
    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 din_clk CLK" *)
    (* X_INTERFACE_PARAMETER = "ASSOCIATED_RESET wfifo_din_rst, FREQ_HZ 16000000" *)
    input  wire din_clk,
    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 dout_clk CLK" *)
    (* X_INTERFACE_PARAMETER = "ASSOCIATED_RESET wfifo_dout_rstn:cpack_reset:elastic_resetn, FREQ_HZ 50000000" *)
    input  wire dout_clk,
    (* X_INTERFACE_IGNORE = "true" *)
    input  wire din_raw_reset,
    (* X_INTERFACE_IGNORE = "true" *)
    input  wire dout_raw_reset,
    (* X_INTERFACE_IGNORE = "true" *)
    input  wire pll_locked,
    (* X_INTERFACE_IGNORE = "true" *)
    input  wire source_ready,
    (* X_INTERFACE_IGNORE = "true" *)
    input  wire elastic_flush_ack,

    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 wfifo_din_rst RST" *)
    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_HIGH, TYPE PERIPHERAL" *)
    output wire wfifo_din_rst,
    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 wfifo_dout_rstn RST" *)
    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW, TYPE PERIPHERAL" *)
    output wire wfifo_dout_rstn,
    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 cpack_reset RST" *)
    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_HIGH, TYPE PERIPHERAL" *)
    output wire cpack_reset,
    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 elastic_resetn RST" *)
    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW, TYPE PERIPHERAL" *)
    output wire elastic_resetn,
    (* X_INTERFACE_IGNORE = "true" *)
    output wire source_write_enable,
    (* X_INTERFACE_IGNORE = "true" *)
    output wire cpack_write_enable,
    (* X_INTERFACE_IGNORE = "true" *)
    output wire reader_data_enable,
    (* X_INTERFACE_IGNORE = "true" *)
    output wire capture_epoch_fence,
    (* X_INTERFACE_IGNORE = "true" *)
    output wire capture_ready,

    // Observability only.  These are level protocol state, never events for
    // datapath use.  They make integration waveforms auditable.
    (* X_INTERFACE_IGNORE = "true" *) output wire source_request,
    (* X_INTERFACE_IGNORE = "true" *) output wire source_fresh,
    (* X_INTERFACE_IGNORE = "true" *)
    output wire destination_fenced
);

    // `source_ready` is generated by the independent FCLK clock monitor.  It
    // is intentionally used only as an asynchronous *assertion* source here:
    // it lets a stopped l_clk quiesce capture without waiting for that clock.
    // Its deassertion never releases state machines directly (see the two
    // local synchronizers below). HDMI has no input or output here.
    wire global_fault = din_raw_reset | dout_raw_reset | ~pll_locked | ~source_ready;

    // Async-assert, synchronous-deassert local reset release.  A raw/monitor
    // fault can assert while either local clock is stopped.  Conversely, a
    // fault deassertion must survive two local clock edges before a state FSM
    // may leave reset, avoiding recovery/removal dependence on cross-domain
    // raw reset timing.
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg [1:0] din_release_sync;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg [1:0] dout_release_sync;
    always @(posedge din_clk or posedge global_fault)
        if (global_fault) din_release_sync <= 2'b00;
        else din_release_sync <= {din_release_sync[0], 1'b1};
    always @(posedge dout_clk or posedge global_fault)
        if (global_fault) dout_release_sync <= 2'b00;
        else dout_release_sync <= {dout_release_sync[0], 1'b1};
    wire din_local_reset = ~din_release_sync[1];
    wire dout_local_reset = ~dout_release_sync[1];

    reg src_request_r, src_fresh_r, src_armed_r;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg [1:0] dst_fenced_sync;

    // Source side: first observe the destination protocol returned to its
    // reset level, then offer a fresh session only after the independent
    // heartbeat has acquired.  Source writes cannot begin until the
    // destination has completed its explicit epoch fence.
    always @(posedge din_clk or posedge din_local_reset) begin
        if (din_local_reset) begin
            src_request_r   <= 1'b0;
            src_fresh_r     <= 1'b0;
            src_armed_r     <= 1'b0;
            dst_fenced_sync <= 2'b00;
        end else begin
            dst_fenced_sync <= {dst_fenced_sync[0], destination_fenced};
            if (!src_armed_r) begin
                // A previous session's high ACK cannot be re-used after a
                // unilateral reset; require its synchronized reset level.
                if (!dst_fenced_sync[1]) src_armed_r <= 1'b1;
            end else if (!src_request_r) begin
                src_request_r <= 1'b1;
            end else if (!src_fresh_r && dst_fenced_sync[1]) begin
                src_fresh_r <= 1'b1;
            end
        end
    end

    localparam [2:0]
        DST_ARM_ZERO = 3'd0,
        DST_WAIT_REQ = 3'd1,
        DST_FENCE    = 3'd2,
        DST_WAIT_ACK = 3'd3,
        DST_WAIT_SRC = 3'd4,
        DST_OPEN     = 3'd5;

    reg [2:0] dst_state;
    reg dst_fenced_r, fence_pulse_r;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg [1:0] src_request_sync;
    (* ASYNC_REG = "TRUE", SHREG_EXTRACT = "NO" *) reg [1:0] src_fresh_sync;

    // Destination side: source offer -> release only local control reset ->
    // fence ingress -> wait for the actual FIFO ACK -> allow fresh source ->
    // expose reader/CPACK data.  In particular, elastic_flush_ack is accepted
    // only after this FSM emitted a fence; an old ACK pulse cannot open data.
    always @(posedge dout_clk or posedge dout_local_reset) begin
        if (dout_local_reset) begin
            dst_state        <= DST_ARM_ZERO;
            dst_fenced_r     <= 1'b0;
            fence_pulse_r    <= 1'b0;
            src_request_sync <= 2'b00;
            src_fresh_sync   <= 2'b00;
        end else begin
            src_request_sync <= {src_request_sync[0], src_request_r};
            src_fresh_sync   <= {src_fresh_sync[0], src_fresh_r};
            fence_pulse_r    <= 1'b0;
            case (dst_state)
                DST_ARM_ZERO: begin
                    // Ignore a high level left over from before local reset.
                    if (!src_request_sync[1]) dst_state <= DST_WAIT_REQ;
                end
                DST_WAIT_REQ: begin
                    if (src_request_sync[1]) dst_state <= DST_FENCE;
                end
                DST_FENCE: begin
                    // pulse is sampled by ingress in this same FCLK domain.
                    fence_pulse_r <= 1'b1;
                    dst_state <= DST_WAIT_ACK;
                end
                DST_WAIT_ACK: begin
                    if (elastic_flush_ack) begin
                        dst_fenced_r <= 1'b1;
                        dst_state <= DST_WAIT_SRC;
                    end
                end
                DST_WAIT_SRC: begin
                    if (src_fresh_sync[1]) dst_state <= DST_OPEN;
                end
                DST_OPEN: begin
                    // Steady capture state.  Raw/monitor faults are handled
                    // asynchronously by the local reset, not by this branch.
                    dst_state <= DST_OPEN;
                end
                default: begin
                    // Illegal encodings must never become an implicit OPEN.
                    // Withdraw the fence acknowledgement and restart the
                    // level protocol from its fail-closed baseline.  This is
                    // deterministic recovery for binary illegal states; an
                    // actual SEU/X-state campaign remains system-level work.
                    dst_fenced_r <= 1'b0;
                    dst_state <= DST_ARM_ZERO;
                end
            endcase
        end
    end

    // Source writer remains reset until the destination has processed the
    // current fence.  This makes the first util_wfifo request after release
    // necessarily originate from its reset baseline (not a stale 1->0 edge).
    // Local reset already asserts asynchronously from global_fault. Do not
    // OR raw cross-domain fault levels back into local data/CE paths: that
    // bypasses the local release synchronizer and fans an unsynchronized
    // source reset through the entire receiver. Fault assertion still clears
    // both release chains without either clock; release remains local-only.
    assign wfifo_din_rst       = din_local_reset | ~src_fresh_r;
    assign source_write_enable = src_fresh_r & ~din_local_reset;

    // CPACK and elastic are both FCLK-domain objects.  They are brought out
    // of reset only for the fence/ACK handshake, but all writes and public
    // reader transfers stay gated until a freshly reset writer has joined.
    wire dst_control_active = (dst_state == DST_FENCE) ||
                              (dst_state == DST_WAIT_ACK) ||
                              (dst_state == DST_WAIT_SRC) ||
                              (dst_state == DST_OPEN);
    assign cpack_reset         = dout_local_reset | ~dst_control_active;
    assign elastic_resetn      = ~cpack_reset;
    assign capture_epoch_fence = fence_pulse_r & ~dout_local_reset;
    // This level is also the return CDC payload. Its register already has
    // asynchronous local reset: keep Q -> first synchronizer D free of logic.
    assign destination_fenced  = dst_fenced_r;

    // The WFIFO reader cannot see an old source request: it is reset through
    // the entire source reset + fence interval, then released before the
    // parser only after src_fresh crossed the CDC synchronizer.
    assign wfifo_dout_rstn    = ~dout_local_reset & (dst_state == DST_OPEN);
    assign cpack_write_enable = ~dout_local_reset & (dst_state == DST_OPEN);
    assign reader_data_enable = ~dout_local_reset & (dst_state == DST_OPEN);
    assign capture_ready      = reader_data_enable & src_fresh_sync[1];

    assign source_request = src_request_r & ~din_local_reset;
    assign source_fresh   = src_fresh_r & ~din_local_reset;

endmodule
