`timescale 1ns/1ps

// Reorder a complete 528-result QPSK batch and deliver exact RFD1/RFE1 bytes.
// No partial payload is exposed. A rejected frame asserts abort_batch; the
// owner must flush the solver before admitting a new frame.
module rfv2_packet_collector #(
    parameter logic [31:0] BUILD_ID = 32'h20261027,
    parameter integer MAX_FRAME_CYCLES = 100000
) (
    input wire clk, input wire resetn, input wire flush,
    input wire cancel_frame,input wire [15:0] cancel_code,
    input wire frame_valid, output wire frame_ready,
    input wire [31:0] frame_id,
    input wire [319:0] public_headers,
    input wire [63:0] s_data, input wire [7:0] s_keep,
    input wire s_valid, output wire s_ready, input wire s_last,
    output logic [63:0] m_data, output wire [7:0] m_keep,
    output wire m_valid, input wire m_ready, output wire m_last,
    output logic abort_batch, output logic frame_done,
    output logic frame_rejected, output logic [15:0] error_code
);
    localparam [31:0] MRF = 32'h3146524d, MOP = 32'h30504f4d;
    localparam [31:0] RFD = 32'h31444652, RFE = 32'h31454652;
    typedef enum logic [4:0] {IDLE,HCRC,HCHECK,HSTORE,COLLECT,
        SYMBOL_READ,SYMBOL_USE,WORD0,WORD1,PAYCHECK,PREFIX,
        CRC_READ,CRC_USE,CRC_STORE,OUT_READ0,OUT_READ1,OUT_PACK,OUT_SEND} state_t;
    state_t state;
    logic [319:0] headers_q;
    logic [31:0] frame_q, hcrc0, hcrc1, payload_crc0, payload_crc1;
    logic [31:0] received_crc0, received_crc1, record_crc;
    (* ram_style="block" *) logic [31:0] record_ram [0:80];
    (* ram_style="block" *) logic [3:0] symbols [0:527];
    logic [527:0] seen;
    logic [9:0] count, symbol_index;
    logic [3:0] byte_index;
    logic [3:0] hstore_index;
    logic [2:0] mop_beat;
    logic [31:0] mop_tag;
    logic [1:0] mop_x0, mop_x1;
    logic [3:0] symbol_ram_q;
    logic [7:0] byte0, byte1;
    logic [31:0] word0, word1;
    logic [5:0] payload_word;
    logic [6:0] prefix_index, crc_word_index, out_word;
    logic [1:0] crc_byte_index;
    logic [31:0] read_word, out_lo;
    logic record_we, record_re;
    logic [6:0] record_waddr, record_raddr;
    logic [31:0] record_wdata;
    // `flush` is generated by the capture/recovery domain.  It is safe for
    // the collector FSM to consume it on clk, but it must not directly gate a
    // RAMB enable/address/reset path: Vivado then traces an asynchronous
    // guard-reset cone into the inferred RAM control pins (REQP-1840).
    //
    // This is deliberately a *local synchronous command fence*.  A command
    // presented in the cycle in which flush is sampled may still perform its
    // physical RAM access; the FSM is cancelled on that same edge and never
    // reaches a PREFIX/CRC/OUT commit from that abandoned context.  Existing
    // committed slots are owned by rfv2_delivery_slot and are not cleared
    // here.  Thus stale storage is permitted, while stale public RFD/RFE
    // records are not.
    logic memory_live_q;
    // Isolate both ports of the symbol RAM from the recovery/guard cone.
    // DONT_TOUCH is intentional: it prevents the implementation pass from
    // folding a guard-resettable FSM predicate back into a RAMB EN/WE pin.
    // The registers use only synchronous collector reset semantics.
    (* DONT_TOUCH = "TRUE" *) logic symbols_we_q, symbols_re_q;
    (* DONT_TOUCH = "TRUE" *) logic [9:0] symbols_waddr_q, symbols_raddr_q;
    (* DONT_TOUCH = "TRUE" *) logic [3:0] symbols_wdata_q;
    logic symbol_forward_q;
    logic [3:0] symbol_forward_data_q;
    wire [3:0] symbol_q = symbol_forward_q ? symbol_forward_data_q : symbol_ram_q;
    logic rejected;
    integer watchdog;

    function automatic [31:0] crc_byte(input [31:0] crc, input [7:0] value);
        reg [31:0] c;
        integer i;
        begin
            c = crc ^ {24'd0,value};
            for (i=0; i<8; i=i+1) c = (c>>1) ^ (c[0] ? 32'hedb88320 : 32'd0);
            crc_byte = c;
        end
    endfunction

    wire [7:0] full_byte0 = {byte0[5:0],symbol_q[1:0]};
    wire [7:0] full_byte1 = {byte1[5:0],symbol_q[3:2]};
    wire [31:0] completed_word0 = word0 | ({24'd0,full_byte0} << (8*symbol_index[3:2]));
    wire [31:0] completed_word1 = word1 | ({24'd0,full_byte1} << (8*symbol_index[3:2]));
    wire [6:0] last_word = rejected ? 7'd4 : 7'd80;
    wire live = resetn && !flush;
    assign frame_ready = live && state == IDLE;
    assign s_ready = live && state == COLLECT;
    assign m_valid = live && state == OUT_SEND;
    assign m_last = m_valid && out_word == last_word;
    assign m_keep = m_last ? 8'h0f : 8'hff;

    // One physical write port and one synchronous read port. Keeping this
    // outside the control FSM prevents mutually exclusive reads/writes from
    // expanding the 324-byte record into flip-flops and wide LUT muxes.
    always_comb begin
        record_we=0; record_re=0; record_waddr=0; record_raddr=0; record_wdata=0;
        case(state)
            HSTORE: begin
                record_we=1;
                if(hstore_index<5) begin
                    record_waddr=7'd5+hstore_index;
                    record_wdata=headers_q[32*hstore_index+:32];
                end else begin
                    record_waddr=7'd43+hstore_index-7'd5;
                    record_wdata=headers_q[160+32*(hstore_index-5)+:32];
                end
            end
            WORD0: begin record_we=1;record_waddr=7'd10+payload_word;record_wdata=word0;end
            WORD1: begin record_we=1;record_waddr=7'd48+payload_word;record_wdata=word1;end
            PREFIX: begin
                record_we=1;record_waddr=prefix_index;
                case(prefix_index)
                    0:record_wdata=rejected?RFE:RFD;
                    1:record_wdata=frame_q;
                    2:record_wdata=BUILD_ID;
                    3:record_wdata=rejected?0:304;
                    default:record_wdata=0;
                endcase
            end
            CRC_STORE:begin record_we=1;record_waddr=4;record_wdata=~record_crc;end
            CRC_READ:begin record_re=1;record_raddr=crc_word_index;end
            OUT_READ0:begin record_re=1;record_raddr=out_word;end
            OUT_READ1:begin record_re=1;record_raddr=out_word==last_word?out_word:out_word+1'b1;end
            default:begin end
        endcase
    end
    always_ff @(posedge clk) begin
        // Do not put resetn/flush in the RAM access condition.  Both only
        // affect this registered local permission at a clock edge.
        if (!resetn)
            memory_live_q <= 1'b0;
        else
            memory_live_q <= !flush;

        // record_* derives only from registered collector state/counters.
        // memory_live_q is the previous local clocked permission, so no
        // asynchronous guard/reset can directly control a RAMB port.
        if (memory_live_q && record_we)
            record_ram[record_waddr] <= record_wdata;
        if (memory_live_q && record_re)
            read_word <= record_ram[record_raddr];
    end

    // A dual-port synchronous command boundary.  The main collector FSM
    // schedules the next symbol read one state early, so this does not reduce
    // accepted MOP II or add a bubble to the SYMBOL_READ/SYMBOL_USE cadence.
    // `symbol_q` intentionally has no reset: it is consumed only after a
    // preceding symbols_re_q command, avoiding an inferred RAMB output reset.
    always_ff @(posedge clk) begin
        if (!resetn || flush) begin
            symbols_we_q <= 1'b0;
            symbols_re_q <= 1'b0;
            symbols_waddr_q <= 10'd0;
            symbols_raddr_q <= 10'd0;
            symbols_wdata_q <= 4'd0;
        end else begin
            symbols_we_q <= 1'b0;
            symbols_re_q <= 1'b0;
            if (state == COLLECT && s_valid && mop_beat == 7) begin
                symbols_we_q <= 1'b1;
                symbols_waddr_q <= mop_tag - 1'b1;
                symbols_wdata_q <= {mop_x1,mop_x0};
                // Launch the first read beside the final write.  The inferred
                // RAM has distinct write/read ports and the addresses differ.
                if (count == 527) begin
                    symbols_re_q <= 1'b1;
                    symbols_raddr_q <= 10'd0;
                end
            end else if (state == SYMBOL_USE && symbol_index != 527) begin
                // Prefetch index+1 while consuming index, preserving cadence.
                symbols_re_q <= 1'b1;
                symbols_raddr_q <= symbol_index + 1'b1;
            end
        end
    end

    always_ff @(posedge clk) begin
        if (symbols_we_q)
            symbols[symbols_waddr_q] <= symbols_wdata_q;
        if (symbols_re_q)
            symbol_ram_q <= symbols[symbols_raddr_q];
        // Keep forwarding outside the RAM read statement.  This preserves a
        // plain inferred block-RAM port while covering the legal tag1-final
        // read/write collision under RAMB READ_FIRST implementation.
        if (symbols_re_q) begin
            symbol_forward_q <= symbols_we_q && symbols_waddr_q == symbols_raddr_q;
            symbol_forward_data_q <= symbols_wdata_q;
        end
    end

    task automatic reject_frame(input [15:0] reason);
        begin
            rejected <= 1'b1;
            frame_rejected <= 1'b1;
            error_code <= reason;
            abort_batch <= 1'b1;
            prefix_index <= 0;
            state <= PREFIX;
        end
    endtask

    always_ff @(posedge clk) begin
        if (!resetn || flush) begin
            state <= IDLE;
            abort_batch <= 0; frame_done <= 0; frame_rejected <= 0; error_code <= 0;
            headers_q <= 0; frame_q <= 0; hcrc0 <= 0; hcrc1 <= 0;
            count <= 0; symbol_index <= 0; byte_index <= 0; hstore_index <= 0;
            mop_beat <= 0; mop_tag <= 0; mop_x0 <= 0; mop_x1 <= 0;
            byte0 <= 0; byte1 <= 0; word0 <= 0; word1 <= 0;
            payload_word <= 0; prefix_index <= 0; crc_word_index <= 0;
            crc_byte_index <= 0; out_word <= 0; out_lo <= 0;
            m_data <= 0; seen <= 0; rejected <= 0; watchdog <= 0;
            payload_crc0 <= 0; payload_crc1 <= 0;
            received_crc0 <= 0; received_crc1 <= 0; record_crc <= 0;
        end else begin
            frame_done <= 0;
            // Channel/pilot failure after valid public headers but before a
            // completed payload must emit RFE1, not silently disappear.
            if(cancel_frame && state!=IDLE && state!=PREFIX && state!=CRC_READ &&
               state!=CRC_USE && state!=CRC_STORE && state!=OUT_READ0 &&
               state!=OUT_READ1 && state!=OUT_PACK && state!=OUT_SEND)
                reject_frame(cancel_code==0 ? 16'h0030 : cancel_code);
            else case (state)
                IDLE: if (frame_valid) begin
                    headers_q <= public_headers; frame_q <= frame_id;
                    hcrc0 <= 32'hffffffff; hcrc1 <= 32'hffffffff;
                    byte_index <= 0; count <= 0; mop_beat <= 0; seen <= 0;
                    rejected <= 0; frame_rejected <= 0; error_code <= 0;
                    abort_batch <= 0; watchdog <= 0; state <= HCRC;
                end
                HCRC: begin
                    hcrc0 <= crc_byte(hcrc0, headers_q[8*byte_index +: 8]);
                    hcrc1 <= crc_byte(hcrc1, headers_q[160+8*byte_index +: 8]);
                    if (byte_index == 15) state <= HCHECK;
                    else byte_index <= byte_index + 1'b1;
                end
                HCHECK: begin
                    if (BUILD_ID == 0 || headers_q[31:0] != MRF || headers_q[191:160] != MRF ||
                        headers_q[63:32] != 32'h00010001 || headers_q[223:192] != 32'h00010101 ||
                        headers_q[95:64] != frame_q || headers_q[255:224] != frame_q ||
                        headers_q[127:96] != 128 || headers_q[287:256] != 128 ||
                        headers_q[159:128] != ~hcrc0 || headers_q[319:288] != ~hcrc1)
                        reject_frame(16'h0001);
                    else begin hstore_index <= 0; state <= HSTORE; end
                end
                HSTORE: begin
                    if (hstore_index == 9) state <= COLLECT;
                    else hstore_index <= hstore_index + 1'b1;
                end
                COLLECT: begin
                    watchdog <= watchdog+1;
                    if (watchdog >= MAX_FRAME_CYCLES-1) reject_frame(16'h0002);
                    else if (s_valid) begin
                        if (s_keep != 8'hff || s_last != (count == 527 && mop_beat == 7))
                            reject_frame(16'h0003);
                        else case (mop_beat)
                            0: if (s_data != {8'd8,8'd2,16'd1,MOP}) reject_frame(16'h0010);
                               else mop_beat <= 1;
                            1: if (s_data[63:32] != 2 || s_data[31:0] == 0 || s_data[31:0] > 528)
                                   reject_frame(16'h0011);
                               else if (seen[s_data[9:0]-1'b1]) reject_frame(16'h0012);
                               else begin mop_tag <= s_data[31:0]; mop_beat <= 2; end
                            2: if (s_data != {32'd64,16'h8000,16'd0}) reject_frame(16'h0013);
                               else mop_beat <= 3;
                            3: if (s_data[31:16] != 0 || s_data[7:0] > 3 || s_data[15:8] > 3)
                                   reject_frame(16'h0014);
                               else begin mop_x0 <= s_data[1:0]; mop_x1 <= s_data[9:8]; mop_beat <= 4; end
                            4: mop_beat <= 5;
                            5: mop_beat <= 6;
                            6: if (s_data != 0) reject_frame(16'h0015);
                               else mop_beat <= 7;
                            7: if (s_data != {BUILD_ID,32'd0}) reject_frame(16'h0016);
                               else begin
                                   seen[mop_tag-1'b1] <= 1'b1;
                                   mop_beat <= 0;
                                   count <= count+1'b1;
                                   if (count == 527) begin
                                       symbol_index <= 0; byte0 <= 0; byte1 <= 0;
                                       word0 <= 0; word1 <= 0; payload_word <= 0;
                                       payload_crc0 <= 32'hffffffff; payload_crc1 <= 32'hffffffff;
                                       state <= SYMBOL_READ;
                                   end
                               end
                            default: reject_frame(16'h0017);
                        endcase
                    end
                end
                SYMBOL_READ: state <= SYMBOL_USE;
                SYMBOL_USE: begin
                    byte0 <= full_byte0; byte1 <= full_byte1;
                    if (symbol_index[1:0] == 3) begin
                        word0 <= completed_word0; word1 <= completed_word1;
                        if (symbol_index < 512) begin
                            payload_crc0 <= crc_byte(payload_crc0,full_byte0);
                            payload_crc1 <= crc_byte(payload_crc1,full_byte1);
                        end
                    end
                    if (symbol_index[3:0] == 15) state <= WORD0;
                    else begin symbol_index <= symbol_index+1'b1; state <= SYMBOL_READ; end
                end
                WORD0: state <= WORD1;
                WORD1: begin
                    word0 <= 0; word1 <= 0; payload_word <= payload_word+1'b1;
                    if (symbol_index == 527) begin
                        received_crc0 <= word0; received_crc1 <= word1; state <= PAYCHECK;
                    end else begin symbol_index <= symbol_index+1'b1; state <= SYMBOL_READ; end
                end
                PAYCHECK: if (received_crc0 != ~payload_crc0 || received_crc1 != ~payload_crc1)
                    reject_frame(16'h0020);
                    else begin prefix_index <= 0; state <= PREFIX; end
                PREFIX: begin
                    if (prefix_index == 4) begin
                        record_crc <= 32'hffffffff; crc_word_index <= 0;
                        crc_byte_index <= 0; state <= CRC_READ;
                    end else prefix_index <= prefix_index+1'b1;
                end
                CRC_READ: state <= CRC_USE;
                CRC_USE: begin
                    record_crc <= crc_byte(record_crc,read_word[8*crc_byte_index +: 8]);
                    if (crc_byte_index == 3) begin
                        crc_byte_index <= 0;
                        if ((rejected && crc_word_index == 3) || (!rejected && crc_word_index == 80))
                            state <= CRC_STORE;
                        else begin
                            crc_word_index <= crc_word_index == 3 ? 7'd5 : crc_word_index+1'b1;
                            state <= CRC_READ;
                        end
                    end else crc_byte_index <= crc_byte_index+1'b1;
                end
                CRC_STORE: begin out_word <= 0; state <= OUT_READ0; end
                OUT_READ0: state <= OUT_READ1;
                OUT_READ1: begin
                    out_lo <= read_word;
                    state <= OUT_PACK;
                end
                OUT_PACK: begin
                    if (out_word == last_word) m_data <= {32'd0,out_lo};
                    else m_data <= {read_word,out_lo};
                    state <= OUT_SEND;
                end
                OUT_SEND: if (m_ready) begin
                    if (out_word == last_word) begin frame_done <= 1; state <= IDLE; end
                    else begin out_word <= out_word+2; state <= OUT_READ0; end
                end
                default: state <= IDLE;
            endcase
        end
    end
endmodule
